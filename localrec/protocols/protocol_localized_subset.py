from pyworkflow import VERSION_1_1
from pyworkflow.protocol.params import PointerParam, FloatParam
from pwem.protocols import ProtParticles
from pwem.objects import SetOfParticles

class ProtParticleSubset(ProtParticles):
    """
    Creates a subset of particles by selecting only those original particles
    for which at least one associated sub-particle exists.

    AI Generated:

    Particle Subset by Subparticles (ProtParticleSubset) — User Manual

        Overview

        The ProtParticleSubset protocol extracts from an input particle set
        only those particles that are represented in a corresponding
        sub-particle set.

        In localized reconstruction workflows, sub-particles are generated
        from original particles by extracting localized regions of interest.
        Not every original particle necessarily contributes valid
        sub-particles. This protocol identifies which parent particles did
        contribute and creates a reduced particle set containing only those
        relevant originals.

        Inputs

        The protocol requires two inputs.

        The first input is the original set of particles from which the final
        subset will be extracted.

        The second input is a set of sub-particles previously generated by a
        localized extraction workflow. Each sub-particle contains coordinate
        metadata that stores the identifier of its parent particle.

        Selection Strategy

        The protocol scans all input sub-particles and reads the parent
        particle identifier stored in the coordinate information.

        A list of unique parent particle identifiers is built so that each
        original particle is considered only once, even if multiple
        sub-particles were extracted from it.

        The original input particle set is then traversed, and every particle
        whose identifier appears in that parent list is copied to the output
        subset.

        Output

        The output is a new particle set containing only those original
        particles that produced at least one valid sub-particle.

        The output preserves the metadata and acquisition information from the
        original input particle set, allowing it to be used directly in later
        processing steps.

        Validation

        The protocol checks that the provided sub-particle input contains the
        expected provenance metadata generated by a localized extraction
        protocol.

        If that metadata is missing, execution is considered invalid because
        the parent-child relationship between particles and sub-particles
        cannot be reliably reconstructed.

        Practical Use

        This protocol is useful when downstream analyses should be restricted
        only to particles that successfully contributed localized signal.

        Typical applications include comparing parent particles of successful
        localized reconstructions, generating reduced datasets for refinement,
        or excluding particles that failed to yield valid sub-particle
        coordinates.

        Final Perspective

        ProtParticleSubset provides a simple but important bridge between
        localized sub-particle analysis and original particle-level datasets.

        By tracing sub-particles back to their parent particles, it enables
        biologically meaningful filtering of the original dataset based on
        localized reconstruction success.
    """
    _label = 'particles subset by subparticles'
    _lastUpdateVersion = VERSION_1_1
    OUTPUTPARTICLESNAME = "outputParticles"
    _possibleOutputs = {OUTPUTPARTICLESNAME: SetOfParticles}
    
    # -------------------------- DEFINE param functions -----------------------
    def _defineParams(self, form):

        form.addSection(label='Input')
        form.addParam('inputParticles', PointerParam,
                      pointerClass='SetOfParticles',
                      label='Input particles',
                      help='Set of particles from which the subset will be taken')
        form.addParam('inputSubParticles', PointerParam,
                      pointerClass='SetOfParticles',
                      label='Input sub-particles',
                      help='Only the particles in this set of sub-particles will be output')

        form.addParallelSection(threads=0, mpi=0)

    # -------------------------- INSERT steps functions -----------------------
    def _insertAllSteps(self):

        self._insertFunctionStep('createOutputStep')

    # -------------------------- STEPS functions ------------------------------
    def createOutputStep(self):

        inputParticles = self.inputParticles.get()
        inputSubParticles = self.inputSubParticles.get()

        outputSet = self._createSetOfParticles()
        outputSet.copyInfo(inputParticles)

        subParticleIds = []

        for subParticle in inputSubParticles:
            coordinate = subParticle.getCoordinate()
            particleId = int(coordinate._micId)
            if not particleId in subParticleIds:
                subParticleIds.append(particleId)

        for particle in inputParticles:
            if particle._objId in subParticleIds:
                outputSet.append(particle)

        self._defineOutputs(**{self.OUTPUTPARTICLESNAME: outputSet})
        self._defineTransformRelation(inputParticles, outputSet)

    # -------------------------- INFO functions -------------------------------
    def _validate(self):
        errors = []
        inputParticles = self.inputSubParticles.get()
        firstSubParticle = inputParticles.getFirstItem()
        if not firstSubParticle.hasAttribute('_transorg'):
            errors.append('The selected input particles does not are the '
                          'output from a localized-extraction protocol.')
        return errors

    def _citations(self):
        return ['Ilca2015', 'Abrishami2020']

    def _summary(self):
        summary = []
        return summary

    def _methods(self):
        return []
