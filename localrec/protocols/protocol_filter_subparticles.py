class ProtFilterSubParts(ProtParticles):
    """
    Filters subparticles generated by localized reconstruction or symmetry
    expansion workflows according to angular redundancy, spatial overlap,
    distance to origin, and preferred viewing direction. The protocol can
    operate either on sets of particles or on sets of coordinates, preserving
    only the subparticles that satisfy the selected geometric criteria.

    AI Generated:

    Filter Subparticles (ProtFilterSubParts) — User Manual
        Overview

        This protocol is designed to remove unwanted or redundant
        subparticles after subparticle generation procedures such as
        symmetry expansion or localized subparticle extraction.

        In many cryo-EM local reconstruction workflows, the raw
        subparticle set contains repeated views, overlapping subparticles,
        or geometrically redundant copies generated by symmetry-related
        operations. While useful during exhaustive exploration, these
        redundant entries can complicate downstream refinement,
        interpretation, and statistical analysis.

        The purpose of this protocol is to retain only the biologically
        relevant subparticles according to user-defined geometric rules.

        Inputs and General Workflow

        The protocol accepts either:

        - a set of particles, or
        - a set of coordinates generated by a localized-subparticles
          workflow.

        The filtering logic is similar for both input types.

        For particle input, the protocol analyzes each particle directly,
        computes the associated angular orientation, groups particles
        according to their parent particle, and applies the selected
        filtering criteria.

        For coordinate input, the protocol reads the associated
        subparticle stored in each coordinate, computes the corresponding
        orientation, applies the same filtering rules, and writes a new
        filtered coordinate set.

        In both cases, filtering is performed independently for the
        subparticles belonging to each parent particle.

        Angular Uniqueness Filtering

        One of the most important options is angular uniqueness.

        The parameter "Angle to keep unique sub-particles" removes
        subparticles that fall within a specified angular distance from
        already accepted ones.

        This is especially useful in symmetry-expanded datasets, where
        several subparticles may represent nearly identical views because
        they lie close to a symmetry axis.

        From a biological perspective, this filter helps reduce redundant
        sampling while preserving orientation diversity.

        Spatial Overlap Filtering

        The minimum-distance filter removes subparticles whose projected
        positions overlap too strongly in image space.

        Subparticles closer than the specified pixel distance are
        considered overlapping.

        This is particularly important when neighboring subparticles
        would otherwise contribute nearly identical local signal.

        In practical terms, this filter reduces oversampling of the same
        local structural region.

        Symmetry-Related Redundancy

        An optional parameter allows overlapping particles to be retained
        if they arise from symmetry-related copies.

        This is useful when the goal is to deliberately preserve all
        symmetry-related observations while still removing only the most
        problematic overlaps.

        In local refinement workflows, this option may help break strict
        symmetry assumptions while preserving biologically meaningful
        repeated observations.

        Distance to Origin Filtering

        The distance-to-origin filter removes subparticles located too
        close to the center of the parent particle.

        This can be useful when central regions are not biologically
        informative or when only peripheral regions of a large assembly
        are relevant.

        Typical use cases include:

        - focusing on membrane-proximal domains,
        - isolating peripheral subunits,
        - excluding central density shared by many subparticles.

        View-Based Filtering

        The protocol allows selection of subparticles according to
        viewing direction.

        Side-view filtering retains only subparticles whose orientation
        falls within a specified angular distance from side views.

        Top-view filtering retains only subparticles whose orientation
        falls within a specified angular distance from top views.

        These filters are particularly useful when local reconstructions
        require enrichment of specific angular classes.

        For biological interpretation, this can help isolate preferred
        orientations associated with particular structural features or
        experimental questions.

        Particle Input Mode

        When the input is a particle set, the protocol processes
        particles ordered by parent particle identity.

        If the input corresponds to subparticles, the parent particle
        identifier is recovered from the coordinate metadata.

        For each subparticle:

        - the original orientation is recovered,
        - Euler angles are computed,
        - geometric filters are applied,
        - accepted particles are written to the output set.

        If provenance information from subparticle generation is missing,
        the protocol issues a warning but continues execution.

        This makes the protocol tolerant of partially incomplete metadata,
        although preserving provenance remains strongly recommended.

        Coordinate Input Mode

        When the input is a coordinate set, the protocol processes
        coordinates grouped by parent particle.

        Each coordinate must contain an associated subparticle object.

        The filtering decision is made using the subparticle orientation,
        while the output consists of filtered coordinates.

        This mode is especially useful when coordinates need to be
        visualized or passed to downstream localized reconstruction
        workflows.

        Validation and Consistency Checks

        The protocol performs basic input validation before execution.

        Particle Sets

        If the input is a particle set, the particles must contain
        projection alignment information.

        Without alignment metadata, the angular filtering operations
        cannot be performed.

        Coordinate Sets

        If the input is a coordinate set, each coordinate must contain
        the associated subparticle metadata.

        Coordinates lacking this information are considered invalid for
        this protocol.

        Outputs and Their Interpretation

        Depending on the input type, the protocol produces either:

        - a filtered particle set, or
        - a filtered coordinate set.

        The output contains only the subparticles that satisfy all
        selected filtering criteria.

        No transformations are modified.

        No new orientations are generated.

        The protocol only performs selective retention or exclusion of
        existing subparticles.

        Practical Recommendations

        In routine biological applications, this protocol is often used
        immediately after subparticle generation.

        Common practical strategies include:

        - applying angular uniqueness to remove symmetry redundancy,
        - applying minimum-distance filtering to avoid overlap,
        - selecting side or top views to enrich desired orientations.

        For exploratory analyses, mild filtering is often preferable.

        For quantitative local refinement, stronger filtering may improve
        stability by reducing geometric redundancy.

        Final Perspective

        For most cryo-EM users, this protocol acts as a geometric
        cleanup stage before local reconstruction or focused refinement.

        Its main value lies in controlling redundancy, overlap, and
        angular sampling so that downstream local analyses are based on
        biologically meaningful and geometrically well-distributed
        subparticles.
    """
    _label = 'filter subparticles'
    _lastUpdateVersion = VERSION_3_0
    OUTPUTCOORDINATESNAME = "outputCoordinates"
    _possibleOutputs = {OUTPUTCOORDINATESNAME: SetOfCoordinates}

    # -------------------------- DEFINE param functions -----------------------
    def _defineParams(self, form):
        form.addSection(label='Input')
        form.addParam('inputSet', PointerParam,
                      pointerClass='SetOfCoordinates, SetOfParticles',
                      label='Input type')
        form.addSection('Sub-particles')
        form.addParam('unique', FloatParam, default=-1,
                      label='Angle to keep unique sub-particles (deg)',
                      help='Keep only unique subparticles within angular '
                           'distance. It is useful to remove overlapping '
                           'sub-particles on symmetry axis.')
        form.addParam('mindist', FloatParam, default=-1,
                      label='Minimum distance between sub-particles (px)',
                      help='In pixels. Minimum distance between the '
                           'subparticles in the image. All overlapping ones '
                           'will be discarded.')
        form.addParam('keepRedundant', BooleanParam, default=False,
                      condition='mindist>0',
                      label='keep overlapping particles in simmetry axis',
                      help="In order to break symmetry constraints, sometimes you want"
                           " all the repetitions of your particle related by symmetry."
                           " but not particles that overlap"
                      )
        form.addParam('distorigin', FloatParam, default=-1,
                      label='Minimum distance to origin (px)',
                      help='In pixels. Minimum distance from subparticle to origin'
                           ' If positive it will drop the subparticles closer'
                           ' to the origin')
        form.addParam('side', FloatParam, default=-1,
                      label='Angle to keep sub-particles from side views (deg)',
                      help='Keep only particles within specified angular '
                           'distance from side views. All others will be '
                           'discarded. ')
        form.addParam('top', FloatParam, default=-1,
                      label='Angle to keep sub-particles from top views (deg)',
                      help='Keep only particles within specified angular '
                           'distance from top views. All others will be '
                           'discarded. ')

        form.addParallelSection(threads=0, mpi=0)

    # -------------------------- INSERT steps functions -----------------------
    def _insertAllSteps(self):

        self._insertFunctionStep('createOutputStep')

    # -------------------------- STEPS functions ------------------------------
    def createOutputStep(self):

        inputSet = self.inputSet.get()
        params = {"unique": self.unique.get(),
                  "mindist": self.mindist.get(),
                  "keepRedundant": self.keepRedundant.get(),
                  "distorigin": self.distorigin.get(),
                  "side": self.side.get(),
                  "top": self.top.get()
                  }
        if isinstance(inputSet, SetOfParticles):
            self._particlesOutputStep(inputSet, params)
        else:
            self._coordinateOutputStep(inputSet, params)

    def _particlesOutputStep(self, inputSet, params):

        outputParts = self._createSetOfParticles()
        outputParts.copyInfo(inputSet)

        lastPartId = None
        particlesList = []
        isSubPart = False;
        missingProvenanceWarned = False
        firstParticle = inputSet.getFirstItem()
        if firstParticle.hasAttribute('_transorg'):
            isSubPart = True;

        print("Processing particles:")
        progress = ProgressBar(total=len(inputSet), fmt=ProgressBar.NOBAR)
        progress.start()

        sys.stdout.flush()
        step = max(100, len(inputSet) // 100)
        for i, particle in enumerate(inputSet.iterItems(orderBy=['_index'])):

            if i % step == 0:
                progress.update(i+1)

            if (isSubPart):
                partId = int(particle._coordinate._micId)
            else:
                partId = int(particle._index)
            if partId != lastPartId:
                lastPartId = partId
                particlesList = []

            subpart = particle.clone()
            if (isSubPart and not missingProvenanceWarned and
                    not has_subparticle_provenance(subpart)):
                self.warning("Subparticle provenance fields "
                             "(_symmetryGroup/_symmetryOperatorId) are "
                             "missing for some items. Continuing without "
                             "failing.")
                missingProvenanceWarned = True
            if (isSubPart):
                _, cAngles = geometryFromMatrix(inv(particle._transorg.getMatrix()))
            else:
                _, cAngles = geometryFromMatrix(inv(particle.getTransform().getMatrix()))
            subpart._angles = cAngles

            if not self._filterParticles(params, particlesList, subpart):
                continue

            particlesList.append(subpart)
            outputParts.append(subpart)

        progress.finish()

        self._defineOutputs(outputParticles=outputParts)
        self._defineSourceRelation(self.inputSet, outputParts)

    def _coordinateOutputStep(self, inputSet, params):

        inputMics = inputSet.getMicrographs()
        outputSet = self._createSetOfCoordinates(inputMics)
        outputSet.copyInfo(inputSet)

        lastPartId = None
        subParticles = []
        coordArr = []
        subParticleId = 0
        missingProvenanceWarned = False

        progress = ProgressBar(len(inputSet), fmt=ProgressBar.NOBAR)
        print("Processing coordinates:")
        progress.start()
        step = max(100, len(inputSet) // 100)
        for i, coord in enumerate(inputSet.iterItems(orderBy=['_subparticle._micId',
                                                     '_micId', 'id'])):
            if i % step == 0:
                progress.update(i+1)

            # The original particle id is stored in the sub-particle as micId
            partId = coord._micId.get()

            # Load the particle if it has changed from the last sub-particle
            if partId != lastPartId:
                self._genOutputCoordinates(subParticles, coordArr, outputSet,
                                           params["mindist"], params["keepRedundant"],
                                           params["distorigin"])
                subParticleId = 0
                coordArr = []
                subParticles = []
                lastPartId = partId

            subParticle = coord._subparticle
            if (not missingProvenanceWarned and
                    not has_subparticle_provenance(subParticle)):
                self.warning("Subparticle provenance fields "
                             "(_symmetryGroup/_symmetryOperatorId) are "
                             "missing for some items. Continuing without "
                             "failing.")
                missingProvenanceWarned = True
            subpart = subParticle.clone()
            _, cAngles = geometryFromMatrix(inv(subParticle._transorg.getMatrix()))
            subpart._angles = cAngles
            subParticleId += 1
            subpart._id = subParticleId
            if not self._filterParticles(params, subParticles, subpart):
                continue
            subParticles.append(subpart)
            coordArr.append(coord.clone())
        progress.finish()
        self._genOutputCoordinates(subParticles, coordArr, outputSet,
                                   params["mindist"], params["keepRedundant"],
                                   params["distorigin"])
        self._defineOutputs(**{self.OUTPUTCOORDINATESNAME: outputSet})
        self._defineTransformRelation(self.inputSet, self.outputCoordinates)

    # -------------------------- INFO functions -------------------------------
    def _validate(self):
        errors = []
        inputSet = self.inputSet.get()
        if isinstance(inputSet, SetOfParticles):
            if not inputSet.hasAlignmentProj():
                errors.append('The selected input particles do not have '
                              'alignment information.')
        else:
            firstCoord = inputSet.getFirstItem()
            if not firstCoord.hasAttribute('_subparticle'):
                errors.append('The selected input coordinates are not the '
                              'output from a localized-subparticles protocol.')

        return errors

    def _citations(self):
        return ['Ilca2015', 'Abrishami2020']

    def _summary(self):
        summary = []
        return summary

    def _methods(self):
        return []

    # -------------------------- UTILS functions ------------------------------

    def _genOutputCoordinates(self, subParticles, coordArr,
                              outputSet, minDist, keepRedundant,
                              distorigin):
        for index, coordinate in enumerate(coordArr):
            if minDist > 0 or distorigin > 0:
                subpart = subParticles[index]
                if not filter_mindist(subParticles, subpart, minDist, keepRedundant):
                    continue
                if not filter_distorigin(subParticles, subpart, distorigin):
                    continue
                outputSet.append(coordinate.clone())
            else:
                outputSet.append(coordinate.clone())

    def _filterParticles(self, params, subParticles, subPart):

        if params["side"] > 0:
            # print("Side Filter")
            if not filter_side(subPart, params["side"]):
                return False
        if params["top"] > 0:
            # print("Top Filter", params["top"])
            if not filter_top(subPart, params["top"]):
                return False
        if params["unique"] >= 0:
            # print(np.degrees(subPart._angles))
            if not filter_unique(subParticles, subPart, params["unique"]):
                return False

        return True
